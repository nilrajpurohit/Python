# Arithmetic Operators
a = 10
b = 3

print(a + b)  # 13
print(a - b)  # 7
print(a * b)  # 30
print(a / b)  # 3.333
print(a // b) # 3
print(a % b)  # 1
print(a ** b) # 1000

# Comparison Operators
print(10 > 5)     # True
print(10 == 5)    # False
print(10 != 5)    # True
print(10 <= 5)    # False

# Logical Operators
x = True
y = False

print(x and y)  # False
print(x or y)   # True
print(not x)    # False